    /**
     * @return Jeu[]
     */
    public function rechercheParTitre(string $titre): array
    {
        return $this->createQueryBuilder('jeu')
            ->andWhere('jeu.titre LIKE :titre')
            ->setParameter('titre', '%'.$titre.'%')
            ->orderBy('jeu.titre', 'ASC')
            ->getQuery()
            ->getResult();
    }

